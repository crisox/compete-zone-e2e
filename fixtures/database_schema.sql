-- Functions
CREATE FUNCTION public.check_event_registration_constraints() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
v_max        int;
  v_deadline   date;
  v_confirmed  int;
BEGIN
  IF (TG_OP = 'INSERT' AND NEW.status = 'CONFIRMED')
     OR (TG_OP = 'UPDATE' AND NEW.status = 'CONFIRMED' AND OLD.status <> 'CONFIRMED') THEN

SELECT max_participants, registration_deadline
INTO v_max, v_deadline
FROM events
WHERE id = NEW.event_id
    FOR UPDATE;

IF v_deadline IS NULL THEN
      RAISE EXCEPTION 'Evento % no existe', NEW.event_id USING errcode = '23514';
END IF;

    IF (now()::date > v_deadline) THEN
      RAISE EXCEPTION 'Inscripciones cerradas para el evento %', NEW.event_id USING errcode = '23514';
END IF;

SELECT count(*) INTO v_confirmed
FROM event_registrations
WHERE event_id = NEW.event_id
  AND status   = 'CONFIRMED';

IF v_confirmed >= v_max THEN
      RAISE EXCEPTION 'Cupos completos para el evento %', NEW.event_id USING errcode = '23514';
END IF;
END IF;

RETURN NEW;
END$$;

COMMENT ON FUNCTION public.check_event_registration_constraints() IS 'Valida cupo y fecha límite al confirmar inscripciones';

CREATE FUNCTION public.set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  NEW.updated_at = now();
RETURN NEW;
END$$;

COMMENT ON FUNCTION public.set_updated_at() IS 'Trigger function: actualiza el campo updated_at con now() en updates';

