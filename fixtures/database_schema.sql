CREATE TABLE public.events_with_counters AS
 SELECT e.id,
    e.organizer_user_id,
    e.title,
    e.description,
    e.date,
    e."time",
    e.end_time,
    e.location_text,
    e.fee,
    e.image_url,
    e.registration_deadline,
    e.max_participants,
    e.featured,
    e.created_at,
    e.updated_at,
    COALESCE(( SELECT count(*) AS count
           FROM public.event_registrations er
          WHERE ((er.event_id = e.id) AND (er.status = 'CONFIRMED'::public.registration_status))), (0)::bigint) AS current_participants
   FROM public.events e;

COMMENT ON VIEW public.events_with_counters IS 'Eventos con campo calculado current_participants (inscripciones confirmadas)';

